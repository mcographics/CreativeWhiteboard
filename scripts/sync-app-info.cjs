const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const info = JSON.parse(fs.readFileSync(path.join(root, "app-info.json"), "utf8"));
const packagePath = path.join(root, "package.json");
const pkg = JSON.parse(fs.readFileSync(packagePath, "utf8"));
pkg.version = info.version;
pkg.description = info.productDescription;
pkg.author = { name: info.companyName };
pkg.license = "UNLICENSED";
pkg.build.appId = info.applicationId;
pkg.build.productName = info.applicationName;
pkg.build.executableName = info.executableName;
pkg.build.copyright = `Copyright © ${info.copyrightYears} ${info.companyName}. All rights reserved.`;
pkg.build.win.icon = info.icon;
pkg.build.win.legalTrademarks = "Third-party product names and file formats belong to their respective owners.";
pkg.build.nsis.installerIcon = info.icon;
pkg.build.nsis.uninstallerIcon = info.icon;
pkg.build.nsis.shortcutName = info.applicationName;
fs.writeFileSync(packagePath, `${JSON.stringify(pkg, null, 2)}\n`);
